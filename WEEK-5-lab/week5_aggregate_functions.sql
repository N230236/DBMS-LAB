USE DBMSLAB;
/*LEVEL1*/
SELECT COUNT(*) AS TOTAL_INCOME_RECORDS FROM INCOME_RECORD;
SELECT SUM(AMOUNT) AS TOTAL_INCOME FROM INCOME_RECORD;
SELECT AVG(AMOUNT) AS AVERAGE_INOCME FROM INCOME_RECORD;
SELECT MAX(AMOUNT) AS HIGHEST_INCOME FROM INCOME_RECORD;
SELECT MIN(AMOUNT) AS LOWEST_INCOME FROM INCOME_RECORD;
/*LEVEL2*/
SELECT CATEGORY_ID,COUNT(*) AS TOTAL_RECORDS FROM INCOME_RECORD GROUP BY CATEGORY_ID;
SELECT CATEGORY_ID,SUM(AMOUNT) AS TOTAL_INCOME FROM INCOME_RECORD GROUP BY CATEGORY_ID;
SELECT CATEGORY_ID,AVG(AMOUNT) AS AVERAGE_INCOME FROM INCOME_RECORD GROUP BY CATEGORY_ID;
SELECT CATEGORY_ID,MAX(AMOUNT) AS HIGHEST_INCOME FROM INCOME_RECORD GROUP BY CATEGORY_ID;
SELECT CATEGORY_ID,MIN(AMOUNT) AS LOWEST_INCOME FROM INCOME_RECORD GROUP BY CATEGORY_ID;
SELECT YEAR_ID,COUNT(*) AS TOTAL_RECORDS FROM INCOME_RECORD GROUP BY YEAR_ID;
SELECT CATEGORY_ID,YEAR_ID,COUNT(*) AS TOTAL_RECORDS FROM INCOME_RECORD GROUP BY CATEGORY_ID,YEAR_ID;
/*LEVEL3*/
SELECT CATEGORY_ID,COUNT(*) AS TOTAL_RECORDS FROM INCOME_RECORD GROUP BY CATEGORY_ID HAVING SUM(AMOUNT)>1000000;
SELECT CATEGORY_ID,AVG(AMOUNT) AS AVERAGE_INCOME FROM INCOME_RECORD GROUP BY CATEGORY_ID HAVING AVG(AMOUNT)>500000;
SELECT YEAR_ID,COUNT(*) AS TOTAL_RECORDS FROM INCOME_RECORD GROUP BY YEAR_ID HAVING COUNT(*) >3;
SELECT CATEGORY_ID,SUM(AMOUNT) AS TOTAL_INCOME FROM INCOME_RECORD GROUP BY CATEGORY_ID ORDER BY TOTAL_INCOME DESC;
SELECT CATEGORY_ID,SUM(AMOUNT) AS TOTAL_INCOME FROM INCOME_RECORD GROUP BY CATEGORY_ID HAVING SUM(AMOUNT)>1000000 ORDER BY TOTAL_INCOME DESC;
SELECT CATEGORY_ID, SUM(AMOUNT) AS TOTAL_INCOME, AVG(AMOUNT) AS AVERAGE_INCOME FROM INCOME_RECORD GROUP BY CATEGORY_ID;
SELECT CATEGORY_ID,YEAR_ID,SUM(AMOUNT) AS TOTAL_INCOME FROM INCOME_RECORD GROUP BY CATEGORY_ID,YEAR_ID ORDER BY TOTAL_INCOME DESC LIMIT 1;
SELECT ir.YEAR_ID,COUNT(DISTINCT ir.TAXPAYER_ID) AS TOTAL_TAXPAYERS FROM INCOME_RECORD ir JOIN TAXPAYER t
	ON ir.TAXPAYER_ID=t.TAXPAYER_ID GROUP BY ir.YEAR_ID;
/*LEVEL4*/
SELECT CATEGORY_ID,SUM(AMOUNT) AS TOTAL_INCOME FROM INCOME_RECORD GROUP BY CATEGORY_ID ORDER BY TOTAL_INCOME DESC LIMIT 1;
SELECT YEAR_ID,SUM(AMOUNT) AS TOTAL_INCOME FROM INCOME_RECORD GROUP BY YEAR_ID ORDER BY TOTAL_INCOME DESC LIMIT 1;
SELECT CATEGORY_ID,AVG(AMOUNT) AS AVERAGE_INCOME FROM INCOME_RECORD GROUP BY CATEGORY_ID ORDER BY AVERAGE_INCOME DESC LIMIT 1;
SELECT CATEGORY_ID,COUNT(*) AS TOTAL_RECORDS FROM INCOME_RECORD GROUP BY CATEGORY_ID HAVING COUNT(*)>2;
SELECT YEAR_ID,SUM(AMOUNT) AS TOTAL_INCOME FROM INCOME_RECORD GROUP BY YEAR_ID HAVING SUM(AMOUNT)>1000000;
SELECT CATEGORY_ID,COUNT(*) AS NUM_OF_RECORDS,SUM(AMOUNT) AS TOTAL_INCOME,AVG(AMOUNT) AS AVERAGE_INCOME,MAX(AMOUNT) AS HIGHEST_INCOME,
	MIN(AMOUNT) AS LOWEST_INCOME FROM INCOME_RECORD GROUP BY CATEGORY_ID;
SELECT CATEGORY_ID, COUNT(*),SUM(AMOUNT),AVG(AMOUNT),MAX(AMOUNT),MIN(AMOUNT) FROM INCOME_RECORD GROUP BY CATEGORY_ID;
