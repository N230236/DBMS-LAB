SELECT * FROM TAXPAYER WHERE TAXPAYER_ID IN(SELECT TAXPAYER_ID FROM INCOME_RECORD WHERE CATEGORY_ID
	IN(SELECT CATEGORY_ID FROM INCOME_CATEGORY WHERE CATEGORY_NAME='BUSINESS'))
    AND
    TAXPAYER_ID NOT IN(SELECT TAXPAYER_ID FROM INCOME_RECORD WHERE CATEGORY_ID
    IN(SELECT CATEGORY_ID FROM INCOME_CATEGORY WHERE CATEGORY_NAME='INVESTMENT'));
SELECT * FROM INCOME_RECORD WHERE AMOUNT>ALL(SELECT AMOUNT FROM INCOME_RECORD WHERE CATEGORY_ID 
	IN( SELECT CATEGORY_ID FROM INCOME_CATEGORY WHERE CATEGORY_NAME='INVESTMENT'));
SELECT * FROM INCOME_RECORD WHERE AMOUNT>ANY(SELECT AMOUNT FROM INCOME_RECORD WHERE CATEGORY_ID 
	IN (SELECT CATEGORY_ID FROM INCOME_CATEGORY WHERE CATEGORY_NAME='INVESTMENT'));
SELECT * FROM TAXPAYER WHERE TAXPAYER_ID IN(SELECT TAXPAYER_ID FROM INCOME_RECORD GROUP BY TAXPAYER_ID
	HAVING SUM(AMOUNT)=(SELECT MAX(TOTAL_AMOUNT) FROM(SELECT TAXPAYER_ID,SUM(AMOUNT) AS TOTAL_AMOUNT
    FROM INCOME_RECORD GROUP BY TAXPAYER_ID)AS TAXPAYER_DETAILS));
SELECT ir.* FROM INCOME_RECORD ir JOIN(SELECT CATEGORY_ID,AVG(AMOUNT) AS AVG_AMOUNT FROM INCOME_RECORD 
	GROUP BY CATEGORY_ID)AS CATEGORY_AVG ON ir.CATEGORY_ID=CATEGORY_AVG.CATEGORY_ID 
    WHERE ir.AMOUNT>CATEGORY_AVG.AVG_AMOUNT;
    
