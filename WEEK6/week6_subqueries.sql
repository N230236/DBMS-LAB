	IN (SELECT CATEGORY_ID FROM INCOME_CATEGORY WHERE category_name='BUSINESS'));
SELECT * FROM INCOME_RECORD WHERE YEAR_ID IN (SELECT YEAR_ID FROM FINANCIAL_YEAR WHERE YEAR_LABEL='2025-2026');
SELECT * FROM INCOME_RECORD WHERE AMOUNT>(SELECT MIN(AMOUNT) FROM INCOME_RECORD WHERE CATEGORY_ID
	IN(SELECT category_id FROM INCOME_CATEGORY WHERE category_name='BUSINESS'));
SELECT * FROM INCOME_RECORD WHERE AMOUNT<(SELECT MAX(AMOUNT) FROM INCOME_RECORD WHERE CATEGORY_ID
	IN(SELECT category_id FROM INCOME_CATEGORY WHERE category_name='SALARY'));
SELECT * FROM TAXPAYER WHERE taxpayer_id IN(SELECT taxpayer_id FROM INCOME_RECORD
	WHERE AMOUNT>(SELECT AVG(AMOUNT) FROM INCOME_RECORD));
SELECT * FROM INCOME_CATEGORY WHERE category_id IN(SELECT CATEGORY_ID FROM INCOME_RECORD);
SELECT * FROM TAXPAYER WHERE TAXPAYER_ID NOT IN(SELECT taxpayer_id FROM INCOME_RECORD WHERE
	CATEGORY_ID IN(SELECT category_id FROM INCOME_CATEGORY WHERE category_name='INVESTMENT'));
    
/*PART A LEVEL 3*/
SELECT * FROM TAXPAYER WHERE taxpayer_id IN(SELECT taxpayer_id FROM INCOME_RECORD
	WHERE AMOUNT=(SELECT MAX(AMOUNT) FROM INCOME_RECORD));
SELECT * FROM INCOME_RECORD WHERE AMOUNT>(SELECT AVG(AMOUNT) FROM INCOME_RECORD WHERE CATEGORY_ID
	IN(SELECT category_id FROM INCOME_CATEGORY WHERE category_name+'BUSINESS'));
SELECT * FROM TAXPAYER WHERE taxpayer_id IN(SELECT taxpayer_id FROM INCOME_RECORD
	WHERE AMOUNT>(SELECT AVG(AMOUNT) FROM INCOME_RECORD));
SELECT * FROM INCOME_RECORD WHERE AMOUNT>ANY(SELECT AMOUNT FROM INCOME_RECORD WHERE CATEGORY_ID
	IN(SELECT category_id FROM INCOME_CATEGORY WHERE category_name='INVESTMENT'));
SELECT * FROM INCOME_RECORD WHERE AMOUNT>ALL(SELECT AMOUNT FROM INCOME_RECORD WHERE CATEGORY_ID
	IN(SELECT category_id FROM INCOME_CATEGORY WHERE category_name='INVESTMENT'));
SELECT * FROM INCOME_CATEGORY WHERE category_id IN(SELECT CATEGORY_ID FROM INCOME_RECORD 
	WHERE AMOUNT=(SELECT MAX(AMOUNT) FROM INCOME_RECORD));
SELECT * FROM FINANCIAL_YEAR WHERE YEAR_ID IN(SELECT YEAR_ID FROM INCOME_RECORD GROUP BY YEAR_ID
	HAVING SUM(AMOUNT)=(SELECT MAX(TOTAL_AMOUNT) FROM(SELECT SUM(AMOUNT) AS TOTAL_AMOUNT FROM INCOME_RECORD
    GROUP BY YEAR_ID)AS YEARLY_TOTAL));
SELECT * FROM TAXPAYER WHERE taxpayer_id IN(SELECT TAXPAYER_ID FROM INCOME_RECORD GROUP BY TAXPAYER_ID
	HAVING SUM(AMOUNT)>(SELECT AVG(TOTAL_AMOUNT) FROM(SELECT TAXPAYER_ID,SUM(AMOUNT) AS TOTAL_AMOUNT
    FROM INCOME_RECORD GROUP BY TAXPAYER_ID)AS TAXPAYER_TOTAL));

